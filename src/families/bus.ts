import { Artifact, Family, Node, Loc, declLoc, isGenerated, ownerOf } from "../artifact";

/** A topic's publishers and subscribers, from the relations and their provenance. */
export function busRows(a: Artifact) {
  const pubs = a.relations?.publishes ?? [];
  const subs = a.relations?.subscribes ?? [];
  const pubLoc = (fn: string, subject: string): Loc | undefined =>
    (a.provenance?.publishes ?? []).find((p) => p.fn === fn && p.subject === subject) ?? declLoc(a, fn);
  const subLoc = (locus: string, handler: string, subject: string): Loc | undefined =>
    (a.provenance?.subscribes ?? []).find((s) => s.locus === locus && s.handler === handler && s.subject === subject) ??
    declLoc(a, `${locus}::${handler}`);
  return { pubs, subs, pubLoc, subLoc };
}

export const bus: Family = {
  id: "hale.bus",
  title: "Bus",
  reads: ["topics", "relations", "provenance", "endpoints", "declares_publish", "endpoint_identity"],
  build(a: Artifact): Node[] {
    const { pubs, subs, pubLoc, subLoc } = busRows(a);
    const topicNames = new Set((a.topics ?? []).map((t) => t.name));
    const nodes: Node[] = [];
    const generated: Node[] = [];
    for (const t of a.topics ?? []) {
      const p = pubs.filter((x) => x.subject === t.name || x.subject === t.subject);
      const s = subs.filter((x) => x.subject === t.name || x.subject === t.subject);
      const flags: string[] = [];
      if (!p.length) flags.push("no publisher in this seed");
      if (!s.length) flags.push("no subscriber in this seed");
      // Who declares the publish (`bus { publish T; }`) and which sites reach the wire.
      const declared = (a.declares_publish ?? []).filter((d) => d.topic === t.name || d.subject === t.subject);
      const sites = (a.endpoint_identity ?? []).filter((e) => e.topic === t.name || e.wire === t.subject);
      (isGenerated(t.name) ? generated : nodes).push({
        label: t.name,
        description: `${t.subject} · ${t.shape}${flags.length ? " · " + flags.join(", ") : ""}`,
        tooltip: `topic ${t.name}\nsubject ${t.subject}\npayload ${t.shape} (${t.payload_hash})\n${p.length} publisher(s), ${s.length} subscriber(s)\ndeclared by ${declared.map((d) => d.locus).join(", ") || "no bus block"}\n${sites.length} publish site(s)`,
        icon: "broadcast",
        tone: flags.length ? "warn" : undefined,
        location: declLoc(a, t.name),
        expanded: true,
        children: [
          ...p.map((x): Node => {
            const n = sites.filter((e) => e.fn === x.fn).length;
            return { label: x.fn, description: `publishes${n > 1 ? ` at ${n} sites` : ""}`, icon: "arrow-right", location: pubLoc(x.fn, x.subject) };
          }),
          ...s.map((x): Node => ({ label: `${x.locus}::${x.handler}`, description: "subscribes", icon: "arrow-left", location: subLoc(x.locus, x.handler, x.subject) })),
          ...declared.filter((d) => !p.some((x) => ownerOf(x.fn) === d.locus)).map((d): Node => ({ label: d.locus, description: "declares publish, no site sends", icon: "circle-outline", tone: "warn", location: d.file && d.span ? { file: d.file, span: d.span } : declLoc(a, d.locus) })),
        ],
      });
    }
    // Subscriptions and publishes on a literal subject no topic declares.
    const literal = new Map<string, Node[]>();
    for (const x of subs) if (!topicNames.has(x.subject) && !(a.topics ?? []).some((t) => t.subject === x.subject)) {
      const l = literal.get(x.subject) ?? [];
      l.push({ label: `${x.locus}::${x.handler}`, description: "subscribes", icon: "arrow-left", location: subLoc(x.locus, x.handler, x.subject) });
      literal.set(x.subject, l);
    }
    for (const x of pubs) if (!topicNames.has(x.subject) && !(a.topics ?? []).some((t) => t.subject === x.subject)) {
      const l = literal.get(x.subject) ?? [];
      l.push({ label: x.fn, description: "publishes", icon: "arrow-right", location: pubLoc(x.fn, x.subject) });
      literal.set(x.subject, l);
    }
    for (const [subject, children] of literal) {
      nodes.push({ label: subject, description: "literal subject", icon: "symbol-string", children, expanded: true });
    }
    if (generated.length) nodes.push({ label: "generated by the compiler", description: `${generated.length}`, icon: "gear", children: generated });
    return nodes;
  },
};
