import { Artifact, Family, Node, declLoc, isGenerated, ownerOf } from "../artifact";

const CLASS_GLOSS: Record<string, string> = {
  syscall: "reaches the operating system",
  block: "may block the thread (I/O, a sleep, a wait)",
  alloc: "allocates in a region",
  publish: "publishes on the bus",
  time: "reads a clock",
  env: "reads the environment",
  ffi: "calls out through @ffi",
  secret_use: "touches a @secret value",
  panic: "may trap",
  recursion: "recurses",
  spawn: "spawns a thread or a process",
  unclassified: "not yet classified by the compiler",
};

/**
 * What every fn does, as the compiler inferred it: the effect classes,
 * rolled up by class and by locus, the classes a program declared
 * itself, and the effect laws (`@effects(only:)`, `@phase_effects`,
 * `forbid reaches(..., effects(...))`) with their verdicts.
 */
export const effects: Family = {
  id: "hale.effects",
  title: "Effects",
  reads: ["effects", "labels", "lowered"],
  build(a: Artifact): Node[] {
    const nodes: Node[] = [];
    const all = Object.entries(a.effects ?? {});
    const own = all.filter(([fn]) => !isGenerated(fn));
    const byClass = new Map<string, string[]>();
    for (const [fn, cls] of own) for (const c of cls) byClass.set(c, [...(byClass.get(c) ?? []), fn]);
    const fnLoc = (fn: string) => declLoc(a, fn);
    nodes.push({
      label: "classes",
      description: [...byClass.entries()].sort((x, y) => y[1].length - x[1].length).map(([c, fns]) => `${c} ${fns.length}`).join(" · ") || "no effects inferred",
      tooltip: "Each effect class and the author's fns that reach it, transitively.",
      icon: "symbol-misc",
      expanded: true,
      children: [...byClass.entries()].sort((x, y) => y[1].length - x[1].length).map(([c, fns]): Node => ({
        label: c,
        description: `${fns.length} fn(s)${CLASS_GLOSS[c] ? ` · ${CLASS_GLOSS[c]}` : ""}`,
        icon: c === "syscall" || c === "ffi" ? "globe" : c === "block" ? "watch" : c === "publish" ? "broadcast" : c === "alloc" ? "database" : "symbol-misc",
        tone: c === "unclassified" ? "warn" : undefined,
        children: fns.sort().map((fn) => ({ label: fn, icon: "symbol-method", location: fnLoc(fn) })),
      })),
    });
    const byLocus = new Map<string, [string, string[]][]>();
    for (const e of own) { const o = ownerOf(e[0]); byLocus.set(o, [...(byLocus.get(o) ?? []), e]); }
    nodes.push({
      label: "by locus",
      description: `${byLocus.size}`,
      icon: "symbol-class",
      expanded: true,
      children: [...byLocus.entries()].map(([l, fns]): Node => {
        const union = [...new Set(fns.flatMap(([, c]) => c))].sort();
        return {
          label: l === fns[0]?.[0] ? `fn ${l}` : l,
          description: union.join(", "),
          tooltip: `${l}\n${fns.map(([fn, c]) => `${fn.slice(l === fn ? 0 : l.length + 2)}: ${c.join(", ")}`).join("\n")}`,
          icon: l === fns[0]?.[0] ? "symbol-method" : "symbol-class",
          location: declLoc(a, l),
          children: l === fns[0]?.[0] && fns.length === 1 ? [] : fns.map(([fn, c]) => ({ label: fn.slice(l.length + 2) || fn, description: c.join(", "), icon: "symbol-method", location: fnLoc(fn) })),
        };
      }),
    });
    const labels = Object.entries(a.labels ?? {});
    if (labels.length) {
      const classes = [...new Set(labels.flatMap(([, c]) => c))];
      nodes.push({
        label: "declared classes",
        description: classes.join(", "),
        tooltip: "Effect classes the program names itself (`effect money;`): the fns that are sources of each (`@effects(is: {money})`).",
        icon: "tag",
        expanded: true,
        children: classes.map((c) => ({ label: c, description: `sources: ${labels.filter(([, cs]) => cs.includes(c)).map(([fn]) => fn).join(", ")}`, icon: "tag", children: labels.filter(([, cs]) => cs.includes(c)).map(([fn]) => ({ label: fn, icon: "symbol-method", location: fnLoc(fn) })) })),
      });
    }
    const lowered = (a.lowered ?? []).filter((l) => /effects|only effects/.test(l.form));
    if (lowered.length) nodes.push({
      label: "effect laws",
      description: `${lowered.length} · ${lowered.every((l) => l.result === "holds") ? "all hold" : lowered.filter((l) => l.result !== "holds").length + " not holding"}`,
      tooltip: "Every effect assertion as the compiler lowered it to a claim, with its verdict.",
      icon: "law",
      expanded: true,
      children: lowered.map((l) => ({ label: l.form, description: `${l.result} · on ${l.subject}`, icon: l.result === "holds" ? "pass" : "error", tone: l.result === "holds" ? "ok" : "error", location: declLoc(a, l.subject) })),
    });
    const gen = all.length - own.length;
    if (gen) nodes.push({ label: "generated by the compiler", description: `${gen} fn(s) of the api binding and the stdlib`, icon: "gear", children: all.filter(([fn]) => isGenerated(fn)).map(([fn, c]) => ({ label: fn, description: c.join(", "), icon: "gear" })) });
    return nodes;
  },
};
